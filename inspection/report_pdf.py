"""
Vehicle Inspection Report ki PDF banata hai (ReportLab library se).
"""
from io import BytesIO

from django.utils import timezone

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (Image, KeepTogether, Paragraph, SimpleDocTemplate,
                                Spacer, Table, TableStyle)

STATUS_COLORS = {
    "no_change": colors.HexColor("#1f8a4c"),
    "minor": colors.HexColor("#c77700"),
    "damage": colors.HexColor("#c62828"),
    "unclear": colors.HexColor("#5c6b7a"),
}

INK = colors.HexColor("#0f0f12")
GOLD = colors.HexColor("#b08d4f")

DISCLAIMER = (
    "This report was generated by an AI-assisted inspection tool. Results highlight "
    "<b>potential</b> changes between photos and must be confirmed by a staff member. "
    "It is not a legal or insurance-grade assessment."
)


def _img(path, width):
    """Photo ko PDF mein fit karne ke liye aspect ratio ke saath scale karo."""
    img = Image(path)
    ratio = img.imageHeight / float(img.imageWidth)
    img.drawWidth = width
    img.drawHeight = width * ratio
    return img


def build_pdf(inspection):
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm,
                            topMargin=15 * mm, bottomMargin=15 * mm,
                            title=f"Vehicle Inspection Report {inspection.report_number}")
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Title"], fontName="Times-Bold", fontSize=24, leading=28,
                        spaceAfter=4, alignment=0, textColor=INK)
    brand = ParagraphStyle("brand", parent=styles["Normal"], fontName="Times-Roman", fontSize=10,
                           textColor=GOLD, spaceAfter=6)
    small = ParagraphStyle("small", parent=styles["Normal"], fontSize=8.5, textColor=colors.grey)
    normal = styles["Normal"]
    h3 = ParagraphStyle("h3", parent=styles["Heading3"], spaceBefore=6, spaceAfter=4)

    rule = Table([[""]], colWidths=[180 * mm], rowHeights=[2])
    rule.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, -1), 0.8, GOLD)]))
    story = [
        Paragraph("A U T O I N S P E C T &nbsp; · &nbsp; PREMIUM VEHICLE INSPECTION", brand),
        Paragraph("Vehicle Inspection Report", h1),
        Paragraph(f"Report No. {inspection.report_number} &nbsp;|&nbsp; "
                  f"Generated {timezone.localtime(inspection.created_at):%d %b %Y, %I:%M %p}", small),
        Spacer(1, 4), rule, Spacer(1, 10),
    ]

    # ---- Vehicle details table ----
    def fmt(d):
        return d.strftime("%d %b %Y") if d else "-"

    details = [
        ["Vehicle", inspection.vehicle, "Plate No.", inspection.plate_number],
        ["Customer", inspection.customer_name, "Inspector", inspection.inspector_name or "-"],
        ["Rental start", fmt(inspection.rental_start), "Rental end", fmt(inspection.rental_end)],
    ]
    t = Table(details, colWidths=[28 * mm, 62 * mm, 25 * mm, 65 * mm])
    t.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#faf8f3")),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#e3dccd")),
        ("PADDING", (0, 0), (-1, -1), 5),
    ]))
    story += [t, Spacer(1, 10)]

    # ---- Summary ----
    color = STATUS_COLORS.get(inspection.overall_status, colors.black)
    story.append(Paragraph(
        f'Overall result: <font color="{color.hexval()}"><b>{inspection.get_overall_status_display()}</b></font>',
        ParagraphStyle("res", parent=normal, fontSize=12.5, spaceAfter=6)))

    rows = [["View", "AI finding", "Changed area", "Similarity"]]
    for z in inspection.zones.all():
        rows.append([z.get_zone_display(), z.get_status_display(),
                     f"{z.change_percent:.2f}%", f"{z.similarity:.0f}%"])
    summary = Table(rows, colWidths=[38 * mm, 82 * mm, 30 * mm, 30 * mm])
    style = [
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("BACKGROUND", (0, 0), (-1, 0), INK),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#ead7a8")),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#e3dccd")),
        ("PADDING", (0, 0), (-1, -1), 5),
    ]
    for i, z in enumerate(inspection.zones.all(), start=1):
        style.append(("TEXTCOLOR", (1, i), (1, i), STATUS_COLORS.get(z.status, colors.black)))
        style.append(("FONTNAME", (1, i), (1, i), "Helvetica-Bold"))
    summary.setStyle(TableStyle(style))
    story += [summary, Spacer(1, 10)]

    if inspection.notes:
        story += [Paragraph(f"<b>Notes:</b> {inspection.notes}", normal), Spacer(1, 8)]

    # ---- Har zone ki photos ----
    img_w = 86 * mm
    for z in inspection.zones.all():
        after_path = z.annotated_image.path if z.annotated_image else z.after_image.path
        c = STATUS_COLORS.get(z.status, colors.black)
        photos = Table([
            [Paragraph("<b>Before rental</b>", small), Paragraph("<b>After rental (AI marked)</b>", small)],
            [_img(z.before_image.path, img_w), _img(after_path, img_w)],
        ], colWidths=[img_w + 4 * mm, img_w + 4 * mm])
        photos.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP")]))
        note = "" if z.aligned else " (auto-alignment failed - photo angles differ a lot)"
        block = [
            Paragraph(f'{z.get_zone_display()} — <font color="{c.hexval()}">{z.get_status_display()}</font>', h3),
            photos,
            Paragraph(f"Changed area: {z.change_percent:.2f}% &nbsp; Regions flagged: {z.regions}{note}", small),
        ]
        dets = list(z.detections.all())
        if z.detector and dets:
            det_rows = [["Damage type", "Location (approx.)", "Confidence", "Area", ""]]
            for d in dets:
                det_rows.append([d.get_label_display(), d.part or "-", f"{d.confidence:.0%}",
                                 f"{d.area_percent:.2f}%", "New" if d.is_new else "Already before"])
            det_table = Table(det_rows, colWidths=[34 * mm, 52 * mm, 24 * mm, 22 * mm, 48 * mm])
            det_style = [
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f4f6f8")),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d5dbe1")),
                ("PADDING", (0, 0), (-1, -1), 3),
            ]
            for i, d in enumerate(dets, start=1):
                det_style.append(("TEXTCOLOR", (4, i), (4, i),
                                  STATUS_COLORS["damage"] if d.is_new else STATUS_COLORS["unclear"]))
            det_table.setStyle(TableStyle(det_style))
            block += [Spacer(1, 4), Paragraph(f"AI damage detection ({z.detector}):", small), det_table]
        elif z.detector:
            block.append(Paragraph(f"AI damage detection ({z.detector}): no damage found.", small))
        block.append(Spacer(1, 8))
        story.append(KeepTogether(block))

    story += [Spacer(1, 6), Paragraph(DISCLAIMER, small), Spacer(1, 18),
              Paragraph("Staff signature: ______________________ &nbsp;&nbsp;&nbsp; "
                        "Customer signature: ______________________", normal)]

    doc.build(story)
    return buffer.getvalue()
